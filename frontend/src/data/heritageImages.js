export function resolveHeritageImage(item) {
  if (!item) return TYPE_IMAGES.default;
  const fromSlug = item.slug && HERITAGE_IMAGES[item.slug];
  if (fromSlug) return fromSlug;
  const fromTitle = item.title && TITLE_IMAGES[item.title];
  if (fromTitle) return fromTitle;
  const url = item.image_url;
  if (url && typeof url === 'string' && !url.startsWith('placeholder:')) {
    return url;
  }
  return TYPE_IMAGES[item.type] || TYPE_IMAGES.default;
}
